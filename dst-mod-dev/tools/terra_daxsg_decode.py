def decode(data: bytes) -> bytes:
    """倒序 + 固定替换表。"""
    return bytes(BYTE_MAP.get(b, b) for b in data[::-1])


def looks_protected(data: bytes) -> bool:
    """启发式：泰拉保护文件特征——首字节在已知 cipher 表内 + 长度不变。
    仅作提示，不保证判断（普通 lua 若恰好命中也会误报）。"""
    return len(data) >= 4 and data[0] in BYTE_MAP


def main():
    ap = argparse.ArgumentParser(description='泰拉 DaxSg Lua 解码（倒序+替换表）')
    ap.add_argument('input', help='加密文件 或 目录（配合 --dir）')
    ap.add_argument('output', nargs='?', help='输出文件（单文件模式，缺省自动加 .decoded.lua）')
    ap.add_argument('--dir', action='store_true', help='批量模式：input 为目录，output 为输出目录')
    ns = ap.parse_args()

    if ns.dir:
        src_dir = Path(ns.input)
        out_dir = Path(ns.output) if ns.output else src_dir / 'decoded'
        out_dir.mkdir(parents=True, exist_ok=True)
        n = 0
        for p in sorted(src_dir.rglob('*')):
            if not p.is_file():
                continue
            rel = p.relative_to(src_dir)
            dst = out_dir / (rel.as_posix() + '.decoded.lua')
            dst.parent.mkdir(parents=True, exist_ok=True)
            dst.write_bytes(decode(p.read_bytes()))
            n += 1
        print('批量解码完成: %d 个 -> %s' % (n, out_dir))
        return

    src = Path(ns.input)
    dst = Path(ns.output) if ns.output else src.with_suffix(src.suffix + '.decoded.lua')
    dst.write_bytes(decode(src.read_bytes()))
    print(dst)


if __name__ == '__main__':
    main()
